import http from 'node:http';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve, relative, extname, basename } from 'node:path';

const args = new Map();
for (let i = 2; i < process.argv.length; i += 1) {
  const arg = process.argv[i];
  if (!arg.startsWith('--')) continue;
  const key = arg.slice(2);
  const next = process.argv[i + 1];
  if (next && !next.startsWith('--')) {
    args.set(key, next);
    i += 1;
  } else {
    args.set(key, true);
  }
}

const rootDir = resolve(process.cwd());
const extensionDir = resolve(rootDir, String(args.get('extension-dir') || 'public/chrome-extension'));
const port = Number(args.get('port') || 17891);
const prepareOnly = args.has('prepare-only');
const scanMs = Math.max(300, Number(args.get('scan-ms') || 800));
const pollMs = Math.max(500, Number(args.get('poll-ms') || 1000));
const endpoint = `http://127.0.0.1:${port}/reload-version`;
const manifestPath = join(extensionDir, 'manifest.json');
const configPath = join(extensionDir, 'dev-reload-config.js');
const clientFile = 'dev-reload-client.js';
const bootstrapStart = '// __FILTERFOOD_DEV_RELOAD_BOOTSTRAP__';
const bootstrapEnd = '// __FILTERFOOD_DEV_RELOAD_BOOTSTRAP_END__';
let activeBackgroundWorker = null;
const watchedExtensions = new Set(['.js', '.json', '.html', '.css', '.svg', '.png', '.jpg', '.jpeg', '.webp']);
const ignoredNames = new Set([
  'dev-reload-config.js',
  'chrome-extension.zip'
]);

function fail(message) {
  console.error(`[extension-watch] ${message}`);
  process.exit(1);
}

function ensureExtensionDir() {
  if (!existsSync(extensionDir)) fail(`Extension directory not found: ${extensionDir}`);
  if (!existsSync(manifestPath)) fail(`manifest.json not found in: ${extensionDir}`);
  if (!existsSync(join(extensionDir, clientFile))) {
    fail(`${clientFile} not found in: ${extensionDir}`);
  }
}

function writeDevConfig() {
  const body = [
    "'use strict';",
    '',
    '// Generated by npm run dev:extension. Do not commit this file.',
    'self.__FILTERFOOD_EXTENSION_DEV_RELOAD__ = {',
    '  enabled: true,',
    `  url: ${JSON.stringify(endpoint)},`,
    `  pollMs: ${pollMs}`,
    '};',
    ''
  ].join('\n');
  writeFileSync(configPath, body, 'utf8');
}

function ensureBackgroundBootstrap() {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const worker = manifest?.background?.service_worker;
  if (!worker) fail('manifest.json does not define background.service_worker.');

  const workerPath = join(extensionDir, worker);
  if (!existsSync(workerPath)) fail(`Service worker loader not found: ${workerPath}`);

  const current = readFileSync(workerPath, 'utf8');
  if (current.includes(bootstrapStart)) return worker;

  const bootstrap = [
    bootstrapStart,
    "try {",
    "  importScripts('dev-reload-config.js');",
    "  if (self.__FILTERFOOD_EXTENSION_DEV_RELOAD__ && self.__FILTERFOOD_EXTENSION_DEV_RELOAD__.enabled) {",
    "    importScripts('dev-reload-client.js');",
    "  }",
    "} catch (_) {",
    "  // Local dev reload is optional and disabled when dev-reload-config.js is absent.",
    "}",
    bootstrapEnd,
    ''
  ].join('\n');

  writeFileSync(workerPath, `${bootstrap}${current}`, 'utf8');
  return worker;
}

function listWatchedFiles(dir = extensionDir, output = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      listWatchedFiles(fullPath, output);
      continue;
    }

    if (ignoredNames.has(entry.name)) continue;
    if (/^background-loader-.*\\.js$/.test(entry.name) && entry.name !== activeBackgroundWorker) continue;
    if (!watchedExtensions.has(extname(entry.name).toLowerCase())) continue;
    output.push(fullPath);
  }
  return output;
}

function snapshot() {
  const files = listWatchedFiles();
  const state = new Map();
  for (const file of files) {
    const stats = statSync(file);
    state.set(file, `${stats.mtimeMs}:${stats.size}`);
  }
  return state;
}

function diffSnapshot(previous, next) {
  const changed = [];
  for (const [file, signature] of next) {
    if (previous.get(file) !== signature) changed.push(file);
  }
  for (const file of previous.keys()) {
    if (!next.has(file)) changed.push(file);
  }
  return changed;
}

ensureExtensionDir();
writeDevConfig();
const worker = ensureBackgroundBootstrap();
activeBackgroundWorker = worker;

let version = String(Date.now());
let currentSnapshot = snapshot();

console.log('[extension-watch] FilterFood extension dev reload ready.');
console.log(`[extension-watch] Load unpacked folder: ${extensionDir}`);
console.log(`[extension-watch] Background worker: ${worker}`);
console.log(`[extension-watch] Poll endpoint: ${endpoint}`);

if (prepareOnly) {
  console.log('[extension-watch] Prepared dev reload files. Start npm run dev:extension to keep watching.');
  process.exit(0);
}

const server = http.createServer((request, response) => {
  if (request.method === 'OPTIONS') {
    response.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type',
      'Cache-Control': 'no-store'
    });
    response.end();
    return;
  }

  if (!request.url || !request.url.startsWith('/reload-version')) {
    response.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    response.end('not found');
    return;
  }

  response.writeHead(200, {
    'Content-Type': 'application/json; charset=utf-8',
    'Access-Control-Allow-Origin': '*',
    'Cache-Control': 'no-store'
  });
  response.end(JSON.stringify({ version, time: new Date().toISOString() }));
});

server.listen(port, '127.0.0.1', () => {
  console.log(`[extension-watch] Watching ${extensionDir}`);
});

setInterval(() => {
  try {
    const nextSnapshot = snapshot();
    const changed = diffSnapshot(currentSnapshot, nextSnapshot);
    if (changed.length > 0) {
      currentSnapshot = nextSnapshot;
      version = String(Date.now());
      const names = changed.slice(0, 6).map(file => relative(extensionDir, file));
      const suffix = changed.length > names.length ? ` (+${changed.length - names.length})` : '';
      console.log(`[extension-watch] Change detected: ${names.join(', ')}${suffix}`);
    }
  } catch (error) {
    console.warn(`[extension-watch] Scan failed: ${error.message}`);
  }
}, scanMs);
